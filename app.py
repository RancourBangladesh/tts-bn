import os
import csv
import json
import wave
import glob
import subprocess
import tempfile
from datetime import datetime
from flask import Flask, request, jsonify, render_template, send_from_directory

app = Flask(__name__)

# Configuration
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATASET_DIR = os.path.join(BASE_DIR, 'dataset')
RECORDINGS_DIR = os.path.join(DATASET_DIR, 'recordings')

# Use optimized dataset prompts by default (generated by optimize_dataset.py)
OPTIMIZED_PROMPTS_FILE = os.path.join(BASE_DIR, 'optimized_dataset', 'recording_prompts.csv')
OLD_PROMPTS_FILE = os.path.join(DATASET_DIR, 'prompts', 'prompts.csv')

# Use optimized prompts if available, otherwise fall back to old prompts
if os.path.exists(OPTIMIZED_PROMPTS_FILE):
    PROMPTS_FILE = OPTIMIZED_PROMPTS_FILE
    print(f"✓ Using optimized dataset prompts: {OPTIMIZED_PROMPTS_FILE}")
else:
    PROMPTS_FILE = OLD_PROMPTS_FILE
    print(f"⚠ Optimized dataset not found, using: {OLD_PROMPTS_FILE}")
    print(f"  Run 'python optimize_dataset.py' to generate optimized prompts")

METADATA_FILE = os.path.join(RECORDINGS_DIR, 'metadata.jsonl')

# Create directories
os.makedirs(RECORDINGS_DIR, exist_ok=True)


def load_prompts():
    """Load prompts from CSV file."""
    prompts = []
    if os.path.exists(PROMPTS_FILE):
        with open(PROMPTS_FILE, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                # Ensure all fields exist (handle different CSV formats)
                prompt = {
                    'prompt_id': row.get('prompt_id', ''),
                    'text': row.get('text', ''),
                    'status': row.get('status', 'pending'),
                    'type': row.get('type', 'sentence')  # Default to 'sentence' if not present
                }
                prompts.append(prompt)
    return prompts


def save_prompts(prompts):
    """Save prompts to CSV file."""
    if prompts:
        with open(PROMPTS_FILE, 'w', encoding='utf-8', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=['prompt_id', 'type', 'text', 'status'])
            writer.writeheader()
            writer.writerows(prompts)


def get_audio_duration(filepath):
    """Get duration of audio file in seconds."""
    try:
        with wave.open(filepath, 'rb') as w:
            frames = w.getnframes()
            rate = w.getframerate()
            return frames / float(rate)
    except Exception:
        return None


def is_safe_path(base_dir, path):
    """Check if path is safe (no path traversal)."""
    # Resolve to absolute paths
    base = os.path.abspath(base_dir)
    target = os.path.abspath(path)
    # Ensure target is within base directory
    return target.startswith(base + os.sep) or target == base


def convert_to_wav(input_path, output_path):
    """Convert audio file to WAV format (22kHz, mono, 16-bit optimized for training)."""
    # Validate paths to prevent command injection
    if not is_safe_path(DATASET_DIR, input_path):
        print(f"Security error: Invalid path")
        return False
    
    if not (is_safe_path(DATASET_DIR, output_path) or output_path.startswith('/tmp/')):
        print(f"Security error: Invalid output path")
        return False
    
    try:
        subprocess.run([
            'ffmpeg', '-y', '-i', input_path,
            '-ar', '22050', '-ac', '1', '-c:a', 'pcm_s16le',
            output_path
        ], capture_output=True, check=True)
        return True
    except Exception as e:
        print(f"Conversion error: {e}")
        return False


def append_metadata(metadata):
    """Append metadata to JSONL file."""
    with open(METADATA_FILE, 'a', encoding='utf-8') as f:
        f.write(json.dumps(metadata, ensure_ascii=False) + '\n')


