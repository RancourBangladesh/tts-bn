def generate_sentences_from_templates(count: int = 15000) -> List[Sentence]:
    """
    Generate additional natural Bengali sentences using ONLY meaningful, 
    pre-written sentences. No random word combinations that create nonsense.
    """
    import random
    random.seed(42)  # Reproducible generation
    
    generated = []
    seen_texts = set()
    
    # First, add all meaningful pre-written sentences
    for i, text in enumerate(MEANINGFUL_SENTENCES, 1):
        if text not in seen_texts:
            seen_texts.add(text)
            sent = Sentence(
                id=f"meaningful_{i:05d}",
                text=text,
                original_text=text,
                source="meaningful_sentences",
                style="conversational"
            )
            generated.append(sent)
    
    # Generate from semantic templates (these make grammatical sense)
    template_count = 0
    max_attempts = count * 3
    while len(generated) < count and template_count < max_attempts:
        template_item = random.choice(SEMANTIC_TEMPLATES)
        template_count += 1
        
        try:
            # Handle both tuple format and string format
            if isinstance(template_item, tuple):
                template = template_item[0]
            else:
                template = template_item
            
            text = template
            
            # Only fill in templates that make semantic sense
            if '{name}' in text:
                text = text.replace('{name}', random.choice(TEMPLATE_NAMES))
            if '{place}' in text:
                text = text.replace('{place}', random.choice(TEMPLATE_PLACES))
            if '{food}' in text:
                text = text.replace('{food}', random.choice(TEMPLATE_FOODS))
            if '{time}' in text:
                text = text.replace('{time}', random.choice(TEMPLATE_TIMES))
            if '{weather}' in text:
                text = text.replace('{weather}', random.choice(TEMPLATE_WEATHER))
            if '{activity}' in text:
                text = text.replace('{activity}', random.choice(TEMPLATE_ACTIVITIES))
            if '{adjective}' in text:
                text = text.replace('{adjective}', random.choice(TEMPLATE_ADJECTIVES))
            
            # Skip if has unfilled placeholders or already exists
            if '{' in text or text in seen_texts:
                continue
            
            seen_texts.add(text)
            sent = Sentence(
                id=f"semantic_{len(generated)+1:05d}",
                text=text,
                original_text=text,
                source="semantic_template",
                style="conversational"
            )
            generated.append(sent)
        except Exception:
            continue
    
    # Add coverage sentences for rare phonemes
    for i, text in enumerate(COVERAGE_SENTENCES, 1):
        if text not in seen_texts:
            seen_texts.add(text)
            sent = Sentence(
                id=f"coverage_{i:03d}",
                text=text,
                original_text=text,
                source="coverage_sentences",
                style="balanced"
            )
            generated.append(sent)
    
    return generated


