@app.route('/api/prompts/<prompt_id>')
def get_prompt(prompt_id):
    """Get a specific prompt."""
    prompts = load_prompts()
    for prompt in prompts:
        if prompt['prompt_id'] == prompt_id:
            return jsonify({'ok': True, 'prompt': prompt})
    return jsonify({'ok': False, 'error': 'Prompt not found'}), 404


@app.route('/api/prompts/<prompt_id>/status', methods=['POST'])
def update_prompt_status(prompt_id):
    """Update prompt status."""
    data = request.get_json()
    new_status = data.get('status', 'pending')
    
    prompts = load_prompts()
    for prompt in prompts:
        if prompt['prompt_id'] == prompt_id:
            prompt['status'] = new_status
            save_prompts(prompts)
            return jsonify({'ok': True, 'prompt': prompt})
    
    return jsonify({'ok': False, 'error': 'Prompt not found'}), 404


@app.route('/api/save', methods=['POST'])
def save_audio():
    """Save uploaded audio recording."""
    speaker = request.form.get('speaker', 'S01')
    prompt_id = request.form.get('prompt_id', '00000')
    text = request.form.get('text', '')
    prompt_type = request.form.get('type', 'unknown')
    
    audio_file = request.files.get('audio_data')
    if not audio_file:
        return jsonify({'ok': False, 'error': 'No audio data received'})
    
    # Generate filename
    timestamp = datetime.utcnow().strftime('%Y%m%dT%H%M%SZ')
    base_filename = f"{speaker}_{timestamp}_{prompt_id}"
    
    # Use /tmp for temporary file (not in dataset directory)
    with tempfile.NamedTemporaryFile(suffix='.webm', delete=False) as temp_file:
        temp_path = temp_file.name
        audio_file.save(temp_path)
    
    # Final WAV path in recordings directory
    wav_path = os.path.join(RECORDINGS_DIR, f"{base_filename}.wav")
    
    try:
        # Convert to WAV (22kHz mono 16-bit)
        if convert_to_wav(temp_path, wav_path):
            audio_path = wav_path
            filename = f"{base_filename}.wav"
        else:
            # If conversion fails, return error
            return jsonify({'ok': False, 'error': 'Audio conversion failed'})
    finally:
        # Always remove temp file
        if os.path.exists(temp_path):
            os.remove(temp_path)
    
    # Get duration
    duration = get_audio_duration(audio_path) if audio_path.endswith('.wav') else None
    
    # Create metadata
    metadata = {
        'speaker_id': speaker,
        'prompt_id': prompt_id,
        'text': text,
        'type': prompt_type,
        'filename': filename,
        'duration': duration,
        'sample_rate': 22050,  # Training-optimized sample rate
        'bits': 16,
        'accepted': True,
        'timestamp': datetime.utcnow().isoformat()
    }
    
    # Save metadata
    append_metadata(metadata)
    
    # Update prompt status
    prompts = load_prompts()
    for prompt in prompts:
        if prompt['prompt_id'] == prompt_id:
            prompt['status'] = 'done'
            break
    save_prompts(prompts)
    
    return jsonify({
        'ok': True,
        'metadata': metadata,
        'message': f'Saved as {filename}'
    })


@app.route('/api/stats')
def get_stats():
    """Get recording statistics."""
    prompts = load_prompts()
    
    stats = {
        'total_prompts': len(prompts),
        'pending': sum(1 for p in prompts if p.get('status') == 'pending'),
        'done': sum(1 for p in prompts if p.get('status') == 'done'),
        'retry': sum(1 for p in prompts if p.get('status') == 'retry'),
    }
    
    # Count recordings
    recordings = [f for f in os.listdir(RECORDINGS_DIR) if f.endswith('.wav')]
    stats['recordings'] = len(recordings)
    
    # Calculate total duration
    total_duration = 0
    for rec in recordings:
        path = os.path.join(RECORDINGS_DIR, rec)
        dur = get_audio_duration(path)
        if dur:
            total_duration += dur
    
    stats['total_duration_seconds'] = round(total_duration, 2)
    stats['total_duration_minutes'] = round(total_duration / 60, 2)
    
    return jsonify({'ok': True, 'stats': stats})





@app.route('/api/recording/<prompt_id>')
def get_recording(prompt_id):
    """Get a recording by prompt ID."""
    # Search for the recording file
    pattern = os.path.join(RECORDINGS_DIR, f'*_{prompt_id}.wav')
    matches = glob.glob(pattern)
    
    if matches:
        # Return the most recent one
        latest = max(matches, key=os.path.getctime)
        filename = os.path.basename(latest)
        return send_from_directory(RECORDINGS_DIR, filename)
    
    return jsonify({'ok': False, 'error': 'Recording not found'}), 404


@app.route('/api/recording/<prompt_id>', methods=['DELETE'])
def delete_recording(prompt_id):
    """Delete a recording by prompt ID (for re-recording)."""
    # Search for the recording file
    pattern = os.path.join(RECORDINGS_DIR, f'*_{prompt_id}.wav')
    matches = glob.glob(pattern)
    
    deleted_count = 0
    for match in matches:
        if is_safe_path(RECORDINGS_DIR, match):
            try:
                os.remove(match)
                deleted_count += 1
            except OSError:
                pass
    
    # Update prompt status back to pending
    prompts = load_prompts()
    for prompt in prompts:
        if prompt['prompt_id'] == prompt_id:
            prompt['status'] = 'pending'
            break
    save_prompts(prompts)
    
    return jsonify({
        'ok': True,
        'deleted': deleted_count,
        'message': f'Deleted {deleted_count} recording(s)'
    })


